#!/usr/bin/env python3
"""Writes src/core/UcsCategories.inc from the Universal Category System's list
(UCS v8.2.1 Full List.xlsx, public domain, from universalcategorysystem.com's
resources): each subcategory's CatID, category, subcategory, explanation and
synonyms. Standard library only.
Usage: gen-ucs.py "UCS v8.2.1 Full List.xlsx" src/core/UcsCategories.inc"""
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

NS = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"


def cells(path):
    z = zipfile.ZipFile(path)
    strings = ["".join(t.text or "" for t in si.iter(NS + "t"))
               for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall(NS + "si")]
    for row in ET.fromstring(z.read("xl/worksheets/sheet1.xml")).iter(NS + "row"):
        out = {}
        for c in row.findall(NS + "c"):
            col = re.match(r"[A-Z]+", c.get("r")).group()
            v = c.find(NS + "v")
            if v is None:
                t = c.find(".//" + NS + "t")
                out[col] = t.text if t is not None else ""
            else:
                out[col] = strings[int(v.text)] if c.get("t") == "s" else v.text
        yield out


def literal(s):
    s = " ".join((s or "").split())
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    rows = list(cells(sys.argv[1]))
    head = next(i for i, r in enumerate(rows) if r.get("A") == "Category" and r.get("C") == "CatID")
    out = ["// Generated by scripts/gen-ucs.py from the Universal Category System v8.2.1 list (public domain,",
           "// universalcategorysystem.com): CatID, category, subcategory, explanation, synonyms.", ""]
    n = 0
    for r in rows[head + 1:]:
        if not r.get("C"):
            continue
        out.append("{%s, %s, %s, %s, %s}," % tuple(literal(r.get(k)) for k in "CABEF"))
        n += 1
    open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print(n, "subcategories")


if __name__ == "__main__":
    main()
