#!/usr/bin/env bash
# Bakes the GPU compositor's shaders (src/render/shaders/*.vert, *.frag) with Qt's qsb into
# src/render/shaders/GpuShaders.inc, so building Montage needs no shader tools. Run after changing a shader:
#   scripts/bake-gpu-shaders.sh /path/to/Qt/6.x/bin/qsb
# The .qsb format is Qt 6.5's (loaded by every later Qt): SPIR-V, GLSL 330 and ES 300 (texelFetch needs them),
# HLSL 5.0 and MSL 1.2.
set -euo pipefail
qsb="${1:-qsb}"
dir="$(cd "$(dirname "$0")/../src/render/shaders" && pwd)"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
out="$dir/GpuShaders.inc"
{
  echo "// Generated by scripts/bake-gpu-shaders.sh from src/render/shaders; do not edit."
  for f in gpuquad.vert gpucolor.frag gpucomposite.frag gpuoutput.frag; do
    LC_ALL=C.UTF-8 "$qsb" --qsbversion 65 --glsl "300 es,330" --hlsl 50 --msl 12 -o "$tmp/$f.qsb" "$dir/$f"
    name="k$(echo "$f" | sed -E 's/^gpu//; s/\.(vert|frag)$/_\1/; s/(^|_)([a-z])/\U\2/g')Qsb"
    echo "static const unsigned char ${name}[] = {"
    od -An -v -tx1 "$tmp/$f.qsb" | sed -E 's/ ([0-9a-f]{2})/0x\1,/g; s/^/   /'
    echo "};"
  done
} > "$out"
echo "wrote $out"
